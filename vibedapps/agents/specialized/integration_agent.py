    async def specialized_capability(self, **kwargs) -> Any:
        """Integrate all DApp components together."""
        specifications = kwargs.get("specifications", {})
        generation_context = kwargs.get("context")

        if not generation_context:
            raise HTTPException(status_code=400, detail="Generation context required for integration")

        if not generation_context.is_ready_for_integration():
            raise HTTPException(
                status_code=400,
                detail="Context not ready for integration. Ensure contract, backend, and frontend are generated."
            )

        # Generate integration files
        integration_files = {}

        # 1. Environment configuration
        integration_files[".env.example"] = self._generate_env_file(generation_context)
        integration_files[".env"] = self._generate_env_file(generation_context)

        # 2. Contract configuration for frontend
        integration_files["frontend/src/contractConfig.js"] = self._generate_contract_config(generation_context)

        # 3. Web3 Provider for React
        integration_files["frontend/src/Web3Provider.js"] = self._generate_web3_provider(generation_context)

        # 4. Backend contract integration
        integration_files["backend/services/contractService.js"] = self._generate_backend_integration(generation_context)

        # 5. Comprehensive README
        integration_files["README.md"] = self._generate_readme(generation_context)

        # 6. Package.json for root (monorepo setup)
        integration_files["package.json"] = json.dumps({
            "name": generation_context.project_name.lower().replace(" ", "-"),
            "version": "1.0.0",
            "description": generation_context.project_description,
            "scripts": {
                "install:all": "npm install && cd backend && npm install && cd ../frontend && npm install",
                "test": "npx hardhat test",
                "deploy": "npx hardhat run scripts/deploy.js",
                "backend": "cd backend && npm start",
                "frontend": "cd frontend && npm start",
                "dev": "concurrently \"npm run backend\" \"npm run frontend\""
            },
            "devDependencies": {
                "concurrently": "^8.0.0"
            }
        }, indent=2)

        # Store in memory
        await self.memory.store_knowledge(
            self.id, f"integration_{generation_context.project_name}", integration_files
        )

        # Update context
        generation_context.completed_agents.append("IntegrationAgent")
        generation_context.stage = "integrated"

        return {
            "project_name": generation_context.project_name,
            "files": integration_files,
            "integration_complete": True,
            "components_integrated": len(generation_context.contracts) + (1 if generation_context.backend else 0) + (1 if generation_context.frontend else 0)
        }
