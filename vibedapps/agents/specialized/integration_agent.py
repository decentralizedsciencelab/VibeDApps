"""
Integration agent.

Runs last in the pipeline: injects the contract ABI into the backend and
frontend, writes the Web3 wiring, and produces the project-level config,
deploy scripts, and README so the pieces actually talk to each other.
"""

import json
from typing import Any, Dict, Optional

from fastapi import APIRouter, HTTPException

from vibedapps.agents.base_agent import AgentConfig, BaseAgent
from vibedapps.llm.openai_service import OpenAIService
from vibedapps.memory.memory_store import InMemoryStore, MemoryStore


class IntegrationAgent(BaseAgent):
    """Agent specialized for integrating all DApp components together."""

    def __init__(
            self,
            config: Optional[AgentConfig] = None,
            memory_store: Optional[MemoryStore] = None,
            llm_service: Optional[OpenAIService] = None
    ):
        # Default config if not provided
        if not config:
            config = AgentConfig(
                name="Integration Coordinator",
                description="Integrates contract, backend, and frontend components into a cohesive DApp",
                capabilities=["abi-injection", "web3-integration", "typescript-types", "env-config"],
                model="gpt-4o",
                temperature=0.2,
                system_prompt=(
                    "You are a specialized agent for integrating DApp components. "
                    "You excel at tying smart contracts, backend APIs, and frontend UIs together. "
                    "You generate integration code, configuration files, and ensure all components can communicate."
                )
            )

        super().__init__(config, memory_store or InMemoryStore(), llm_service)

        # Register specialized endpoints
        self._register_specialized_endpoints()

    def _register_specialized_endpoints(self):
        """Register specialized endpoints for this agent."""
        router = APIRouter()

        @router.post("/integrate")
        async def integrate_components(specifications: Dict[str, Any]):
            """Integrate all DApp components."""
            return await self.specialized_capability(specifications=specifications)

        # Add the router to the app
        self.app.include_router(router, prefix="/api/integration")

    def _generate_env_file(self, context: Any) -> str:
        """
        Generate .env file with all necessary environment variables.

        Args:
            context: DAppGenerationContext with all component details

        Returns:
            .env file content as string
        """
        env_content = f"""# DApp Environment Configuration
# Generated by Multi-Agent DApp Generator

# Project Configuration
PROJECT_NAME={context.project_name}
NETWORK={context.target_network}

"""

        # Add contract addresses
        if context.contracts:
            env_content += "# Smart Contract Addresses\n"
            for contract in context.contracts:
                contract_var = contract.name.upper().replace(" ", "_")
                address = contract.deployed_address or "0x0000000000000000000000000000000000000000"
                env_content += f"{contract_var}_ADDRESS={address}\n"
            env_content += "\n"

        # Add network configuration
        if context.rpc_url:
            env_content += "# Network Configuration\n"
            env_content += f"RPC_URL={context.rpc_url}\n"
            if context.chain_id:
                env_content += f"CHAIN_ID={context.chain_id}\n"
            env_content += "\n"

        # Add backend configuration
        if context.backend:
            env_content += "# Backend Configuration\n"
            env_content += f"BACKEND_PORT={context.backend.port}\n"
            env_content += f"BACKEND_URL=http://localhost:{context.backend.port}\n"
            env_content += "\n"

        # Add frontend configuration
        if context.frontend:
            env_content += "# Frontend Configuration\n"
            env_content += f"FRONTEND_PORT={context.frontend.port}\n"
            env_content += f"REACT_APP_BACKEND_URL=http://localhost:{context.backend.port if context.backend else 3001}\n"
            if context.contracts:
                env_content += f"REACT_APP_CONTRACT_ADDRESS={context.contracts[0].deployed_address or '0x0000000000000000000000000000000000000000'}\n"
            env_content += "\n"

        # Add custom environment variables from context
        if context.environment_variables:
            env_content += "# Custom Environment Variables\n"
            for key, value in context.environment_variables.items():
                if key not in ["PROJECT_NAME", "NETWORK"]:  # Avoid duplicates
                    env_content += f"{key}={value}\n"

        return env_content

    def _generate_contract_config(self, context: Any) -> str:
        """
        Generate contract configuration file with ABIs and addresses.

        Args:
            context: DAppGenerationContext

        Returns:
            JavaScript/TypeScript config file content
        """
        config_content = """// Contract Configuration
// Auto-generated by Multi-Agent DApp Generator

"""

        # Add each contract's ABI and address
        for contract in context.contracts:
            config_content += f"""
export const {contract.name}Config = {{
  address: process.env.REACT_APP_{contract.name.upper()}_ADDRESS || "{contract.deployed_address or '0x0000000000000000000000000000000000000000'}",
  abi: {json.dumps(contract.abi, indent=2)}
}};
"""

        # Add a combined contracts export
        contract_names = [c.name for c in context.contracts]
        config_content += """

// Combined contracts export
export const contracts = {
"""
        for name in contract_names:
            config_content += f"  {name}: {name}Config,\n"
        config_content += """};

// Network configuration
export const networkConfig = {
  name: process.env.NETWORK || \"""" + context.target_network + """\",
  rpcUrl: process.env.RPC_URL || "",
  chainId: parseInt(process.env.CHAIN_ID || "0")
};
"""

        return config_content

    def _generate_web3_provider(self, context: Any) -> str:
        """
        Generate Web3 provider/context for React applications.

        Args:
            context: DAppGenerationContext

        Returns:
            React context file content
        """
        primary_contract = context.get_primary_contract()
        contract_name = primary_contract.name if primary_contract else "Contract"

        provider_content = """// Web3 Provider Context
// Auto-generated by Multi-Agent DApp Generator

import React, { createContext, useContext, useState, useEffect } from 'react';
import { ethers } from 'ethers';
import { contracts as contractConfigs, networkConfig } from './contractConfig';

const Web3Context = createContext(null);

export const useWeb3 = () => {
  const context = useContext(Web3Context);
  if (!context) {
    throw new Error('useWeb3 must be used within Web3Provider');
  }
  return context;
};

export const Web3Provider = ({ children }) => {
  const [provider, setProvider] = useState(null);
  const [signer, setSigner] = useState(null);
  const [account, setAccount] = useState(null);
  const [contracts, setContracts] = useState({});
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState(null);

  useEffect(() => {
    initializeWeb3();
  }, []);

  const initializeWeb3 = async () => {
    try {
      setLoading(true);
      setError(null);

      // Check if MetaMask is installed
      if (typeof window.ethereum === 'undefined') {
        throw new Error('MetaMask is not installed');
      }

      // Request account access
      await window.ethereum.request({ method: 'eth_requestAccounts' });

      // Create provider and signer
      const web3Provider = new ethers.BrowserProvider(window.ethereum);
      const web3Signer = await web3Provider.getSigner();
      const address = await web3Signer.getAddress();

      setProvider(web3Provider);
      setSigner(web3Signer);
      setAccount(address);

      // Initialize contract instances
      const contractInstances = {};
"""

        # Add contract initialization for each contract
        for contract in context.contracts:
            provider_content += f"""      contractInstances.{contract.name.lower()} = new ethers.Contract(
        contractConfigs.{contract.name}.address,
        contractConfigs.{contract.name}.abi,
        web3Signer
      );
"""

        provider_content += """
      setContracts(contractInstances);
      setLoading(false);
    } catch (err) {
      console.error('Web3 initialization error:', err);
      setError(err.message);
      setLoading(false);
    }
  };

  const connectWallet = async () => {
    await initializeWeb3();
  };

  const disconnectWallet = () => {
    setProvider(null);
    setSigner(null);
    setAccount(null);
    setContracts({});
  };

  const value = {
    provider,
    signer,
    account,
    contracts,
    loading,
    error,
    connectWallet,
    disconnectWallet,
    networkConfig
  };

  return <Web3Context.Provider value={value}>{children}</Web3Context.Provider>;
};
"""

        return provider_content

    def _generate_backend_integration(self, context: Any) -> str:
        """
        Generate backend integration code for interacting with contracts.

        Args:
            context: DAppGenerationContext

        Returns:
            Backend integration code
        """
        primary_contract = context.get_primary_contract()
        if not primary_contract:
            return "// No contract available for backend integration"

        integration_content = f"""// Backend Contract Integration
// Auto-generated by Multi-Agent DApp Generator

const {{ ethers }} = require('ethers');

// Contract configuration
const CONTRACT_ADDRESS = process.env.{primary_contract.name.upper()}_ADDRESS;
const CONTRACT_ABI = {json.dumps(primary_contract.abi, indent=2)};

// Network configuration
const RPC_URL = process.env.RPC_URL || 'http://localhost:8545';
const PRIVATE_KEY = process.env.PRIVATE_KEY; // Should be set in production

class ContractService {{
  constructor() {{
    this.provider = new ethers.JsonRpcProvider(RPC_URL);

    if (PRIVATE_KEY) {{
      this.wallet = new ethers.Wallet(PRIVATE_KEY, this.provider);
      this.contract = new ethers.Contract(CONTRACT_ADDRESS, CONTRACT_ABI, this.wallet);
    }} else {{
      this.contract = new ethers.Contract(CONTRACT_ADDRESS, CONTRACT_ABI, this.provider);
    }}
  }}

  // Read contract state
  async getContractState() {{
    try {{
      // Example: Get basic contract info
      const address = await this.contract.getAddress();
      return {{ address }};
    }} catch (error) {{
      console.error('Error reading contract state:', error);
      throw error;
    }}
  }}

  // Listen to contract events
  listenToEvents(eventName, callback) {{
    this.contract.on(eventName, callback);
  }}

  // Stop listening to events
  removeListener(eventName, callback) {{
    this.contract.off(eventName, callback);
  }}
}}

module.exports = {{ ContractService }};
"""

        return integration_content

